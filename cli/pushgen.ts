// Generates Figma Plugin API JavaScript that can be sent verbatim to
// `use_figma`. The whole point is to remove agent discretion: instead of
// asking the agent to translate inspect output into use_figma calls (which
// it keeps screwing up by skipping bindings), we emit the exact plugin code
// here and the agent's only job is to pipe each script through use_figma.
//
// The scripts are designed to be idempotent (re-runs don't duplicate) and
// self-resolving (each component script looks up variables by name at
// runtime, so they can reference variables a previous script created
// without us having to thread IDs through the JSON output).

import type { TokenCollection, TokenValue } from "./tokens.js";
import type { FigmaVariantProperty } from "./mapper.js";
import type { InspectionResult, ResolvedStyling, Bindings, RenderedChild } from "./inspect.js";

export interface PushScript {
  label: string;
  code: string;
}

export interface PushPlan {
  fileKey: string;
  scripts: PushScript[];
  warnings: string[];
}

// Figma color: { r, g, b } in 0..1, plus optional `a`.
interface RGB {
  r: number;
  g: number;
  b: number;
  a?: number;
}

